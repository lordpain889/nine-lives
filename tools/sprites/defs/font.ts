// Кириллица, совпадающая по форме с латиницей/цифрами
const ALIASES: Record<string, string> = {
  А: 'A', В: 'B', Е: 'E', З: '3', К: 'K', М: 'M', Н: 'H',
  О: 'O', Р: 'P', С: 'C', Т: 'T', У: 'Y', Х: 'X',
};

// Глиф символа → матрица клетки 6×8 (5×7 в левом верхнем углу, цвет 'w')
export function glyphCell(ch: string): Matrix {
  const source = G[ch] ?? G[ALIASES[ch]];
  if (!source) throw new Error(`font: нет глифа для "${ch}"`);
  const cell = blank(FONT_CELL_W, FONT_CELL_H).map((r) => r.split(''));
  source.forEach((row, y) => {
    row.split('').forEach((px, x) => {
      if (px === 'X') cell[y][x] = 'w';
    });
  });
  return cell.map((r) => r.join(''));
}

export function buildFontFrames(): Matrix[] {
  return FONT_CHARSET.split('').map((ch) => glyphCell(ch));
}
